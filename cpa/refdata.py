def cm_period_months(cost_eok):
    """공사비(억원) → 평균 건설사업관리기간(개월), 직선보간."""
    t = CM_PERIOD_TABLE
    if cost_eok <= t[0][0]:
        return float(t[0][1])
    if cost_eok >= t[-1][0]:
        return float(t[-1][1])
    for (x0, y0), (x1, y1) in zip(t, t[1:]):
        if x0 <= cost_eok <= x1:
            return y0 + (y1 - y0) * (cost_eok - x0) / (x1 - x0)


